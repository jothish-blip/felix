package provenance

import (
	"time"
)

// VCSInfo captures source-control revision and dirty-state metadata.
type VCSInfo struct {
	// BuildRevision is the commit SHA embedded at build/compile time (via debug.ReadBuildInfo or ldflags).
	BuildRevision string `json:"build_revision,omitempty"`
	// BuildDirty indicates if the compile-time worktree had uncommitted changes.
	BuildDirty *bool `json:"build_dirty,omitempty"`
	// BuildTime is the UTC timestamp when the binary was built.
	BuildTime string `json:"build_time,omitempty"`

	// RuntimeRevision is the source-control commit SHA detected from the runtime environment or checkout.
	RuntimeRevision string `json:"runtime_revision,omitempty"`
	// RuntimeDirty indicates if the runtime checkout has uncommitted or modified files.
	RuntimeDirty *bool `json:"runtime_dirty,omitempty"`

	// VCSSource describes how revision information was obtained ("build_info", "git_worktree", "environment", "unavailable").
	VCSSource string `json:"vcs_source,omitempty"`
}

// ArtifactProvenance documents an output report or artifact generated by an assessment run.
type ArtifactProvenance struct {
	Format    string `json:"format"`              // "HTML", "JSON", "SARIF"
	Path      string `json:"path"`                // Relative or absolute file path
	Generated bool   `json:"generated"`           // Whether the artifact was successfully written
	Error     string `json:"error,omitempty"`     // Error message if artifact write failed
	Digest    string `json:"digest,omitempty"`    // SHA-256 content digest of the written file
	SizeBytes int64  `json:"size_bytes,omitempty"`// File size in bytes
}

// AssessmentProvenance retains sufficient trustworthy metadata to establish which revision,
// build, configuration, scope, and execution context produced an assessment result.
type AssessmentProvenance struct {
	// Assessment & Execution Identity
	ExecutionID   string `json:"execution_id"`
	AssessmentID  string `json:"assessment_id,omitempty"`
	AssessmentRef string `json:"assessment_ref,omitempty"`

	// FELIX Version & Build
	FelixVersion string `json:"felix_version"`
	BuildID      string `json:"build_id,omitempty"`

	// Source-Control Revision
	VCS VCSInfo `json:"vcs"`

	// Timestamps (UTC)
	StartedAt   time.Time  `json:"started_at"`
	CompletedAt *time.Time `json:"completed_at,omitempty"`
	DurationMs  int64      `json:"duration_ms,omitempty"`

	// Execution Status & Failure Classification
	Status          string `json:"status"`                     // QUEUED, RUNNING, COMPLETED, COMPLETED_WITH_ERRORS, FAILED, CANCELLED, INTERRUPTED
	FailureCategory string `json:"failure_category,omitempty"` // SUCCESS, SECURITY_VIOLATION, TOOL_FAILURE, INCOMPLETE
	ExitCode        int    `json:"exit_code"`

	// Configuration & Deterministic Digest
	ConfigDigest    string         `json:"config_digest,omitempty"`
	SanitizedConfig map[string]any `json:"sanitized_config,omitempty"`

	// Target & Scope Identity
	TargetIdentity  string   `json:"target_identity,omitempty"`
	ScopeMode       string   `json:"scope_mode,omitempty"`
	ApprovedTargets []string `json:"approved_targets,omitempty"`

	// Policy Identity & Digest
	PolicyIdentity string `json:"policy_identity,omitempty"`
	PolicyDigest   string `json:"policy_digest,omitempty"`
	PolicyStatus   string `json:"policy_status,omitempty"` // PASS, FAIL, NONE, ERROR

	// Baseline Reference
	BaselineRef         string `json:"baseline_ref,omitempty"`
	BaselineExecutionID string `json:"baseline_execution_id,omitempty"`
	BaselineSnapshotID  string `json:"baseline_snapshot_id,omitempty"`

	// Assessment Engines & Coverage
	EnabledEngines    []string `json:"enabled_engines,omitempty"`
	CoveredCategories []string `json:"covered_categories,omitempty"`

	// Generated Artifacts
	Artifacts []ArtifactProvenance `json:"artifacts,omitempty"`

	// Interruption, Recovery, and Completeness
	IsPartial      bool       `json:"is_partial,omitempty"`
	RecoveryAction string     `json:"recovery_action,omitempty"`
	RecoveryReason string     `json:"recovery_reason,omitempty"`
	RecoveredAt    *time.Time `json:"recovered_at,omitempty"`
}
